#!/bin/sh
# Reads GOOGLE_IOS_CLIENT_ID from apps/mobile/.env and writes:
#   - Flutter/GoogleSignIn.xcconfig (build settings)
#   - Runner/Info.plist GIDClientID + Google URL scheme, added or updated in
#     place without removing other CFBundleURLTypes (literal — Xcode was not
#     expanding $(GID_URL_SCHEME) into the installed Info.plist)
set -e

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
IOS_ROOT="$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)"
ENV_FILE="${IOS_ROOT}/../.env"
OUT_FILE="${SCRIPT_DIR}/GoogleSignIn.xcconfig"
INFO_PLIST="${IOS_ROOT}/Runner/Info.plist"

write_xcconfig() {
  cat >"$OUT_FILE" <<EOF
// Auto-generated by sync_google_sign_in.sh — do not edit.
GID_CLIENT_ID=$1
GID_URL_SCHEME=$2
EOF
}

apply_info_plist() {
  client_id="$1"
  url_scheme="$2"
  PB=/usr/libexec/PlistBuddy
  $PB -c "Delete :GIDClientID" "$INFO_PLIST" 2>/dev/null || true
  $PB -c "Add :GIDClientID string ${client_id}" "$INFO_PLIST"

  # Add or update ONLY the Google scheme. Other URL types (e.g. the
  # com.rawthrottle.riderlab:// deep link used by Supabase OAuth/recovery)
  # are left untouched.
  if ! $PB -c "Print :CFBundleURLTypes" "$INFO_PLIST" >/dev/null 2>&1; then
    $PB -c "Add :CFBundleURLTypes array" "$INFO_PLIST"
  fi
  i=0
  google_i=""
  google_j=""
  while $PB -c "Print :CFBundleURLTypes:$i" "$INFO_PLIST" >/dev/null 2>&1; do
    j=0
    while scheme=$($PB -c "Print :CFBundleURLTypes:$i:CFBundleURLSchemes:$j" "$INFO_PLIST" 2>/dev/null); do
      case "$scheme" in
        com.googleusercontent.apps.*|'$(GID_URL_SCHEME)')
          google_i="$i"
          google_j="$j"
          ;;
      esac
      j=$((j + 1))
    done
    i=$((i + 1))
  done

  if [ -n "$google_i" ]; then
    $PB -c "Set :CFBundleURLTypes:$google_i:CFBundleURLSchemes:$google_j ${url_scheme}" "$INFO_PLIST"
  else
    $PB -c "Add :CFBundleURLTypes:$i dict" "$INFO_PLIST"
    $PB -c "Add :CFBundleURLTypes:$i:CFBundleTypeRole string Editor" "$INFO_PLIST"
    $PB -c "Add :CFBundleURLTypes:$i:CFBundleURLSchemes array" "$INFO_PLIST"
    $PB -c "Add :CFBundleURLTypes:$i:CFBundleURLSchemes:0 string ${url_scheme}" "$INFO_PLIST"
  fi
}

if [ ! -f "$ENV_FILE" ]; then
  echo "warning: $ENV_FILE missing; Google Sign-In iOS config not set" >&2
  write_xcconfig "" ""
  exit 0
fi

IOS_CLIENT_ID=$(grep -E '^[[:space:]]*GOOGLE_IOS_CLIENT_ID=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '"' | tr -d "'" | tr -d '[:space:]')

if [ -z "$IOS_CLIENT_ID" ] || [ "$IOS_CLIENT_ID" = "123456789-yyyy.apps.googleusercontent.com" ]; then
  echo "warning: set GOOGLE_IOS_CLIENT_ID in apps/mobile/.env for Google Sign-In on iOS" >&2
  write_xcconfig "" ""
  exit 0
fi

case "$IOS_CLIENT_ID" in
  *.apps.googleusercontent.com)
    ID_PART="${IOS_CLIENT_ID%.apps.googleusercontent.com}"
  ;;
  *)
    echo "error: GOOGLE_IOS_CLIENT_ID must end with .apps.googleusercontent.com" >&2
    exit 1
  ;;
esac

GID_URL_SCHEME="com.googleusercontent.apps.${ID_PART}"

write_xcconfig "$IOS_CLIENT_ID" "$GID_URL_SCHEME"
apply_info_plist "$IOS_CLIENT_ID" "$GID_URL_SCHEME"

echo "Google Sign-In iOS config synced (xcconfig + Info.plist URL scheme)"
